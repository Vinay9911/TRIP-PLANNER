"use client";

/**
 * The live trip panel: everything known about the trip, beside the conversation.
 *
 * **The problem this solves is scrolling, not styling.** A chat transcript is
 * chronological, so the map, the photographs and the hotel list scroll away
 * the moment the traveller replies. Asking "and the weather?" pushed the
 * weather off screen by the time it arrived. Anything that describes the
 * *current state of the trip* belongs somewhere that does not move, which is
 * here; the conversation keeps the things that are genuinely a sequence.
 *
 * **Every panel has three states and shows which one it is in.** Empty, with
 * a line saying what to ask for; loading, as a skeleton; or filled. A panel
 * that renders nothing when it has nothing is indistinguishable from a broken
 * one, and the commonest complaint about this app was people not knowing
 * whether a feature existed or had failed.
 *
 * **Provenance is on the panel, not in a footnote.** Flight and hotel prices
 * here are generated - Amadeus withdrew its free tier - and a made-up price
 * rendered in the same style as a real forecast is the most misleading thing
 * this interface could do. Simulated panels say so on their own header, in
 * their own colour, every time.
 */

import { useEffect, useState } from "react";

import {
  IconBed,
  IconCalendar,
  IconInfo,
  IconPin,
  IconPlane,
  IconSun,
  IconUsers,
  IconWallet,
} from "@/components/icons";
import {
  PlaceMap,
  dayColor,
  type BaseLayerName,
  type MappedItem,
} from "@/components/PlaceMap";
import { PlacePhoto } from "@/components/PlacePhoto";
import type { ChatResponse, TripFact, TripState } from "@/lib/api";

/** What a panel currently knows. */
type PanelState = "empty" | "loading" | "ready";

/**
 * A panel shell: title, provenance, and an honest empty state.
 *
 * The `hint` is deliberately phrased as something to say rather than a
 * description of the absence. "Ask about hotels" tells a traveller how to fill
 * it; "No hotel data" tells them nothing they cannot already see.
 */
function Panel({
  title,
  icon,
  state,
  hint,
  fact,
  action,
  ask,
  askLabel = "Ask now",
  onAsk,
  children,
}: {
  title: string;
  icon: React.ReactNode;
  state: PanelState;
  hint: string;
  fact?: TripFact;
  action?: React.ReactNode;
  /** The message the button sends. Omitted when there is nothing sensible
   *  to ask yet - offering "find me a hotel" before a destination is known
   *  just produces a clarifying question. */
  ask?: string;
  askLabel?: string;
  onAsk?: (message: string) => void;
  children?: React.ReactNode;
}) {
  return (
    <section className="overflow-hidden rounded-2xl border border-[var(--color-line)] bg-[var(--color-surface)]">
      <header className="flex items-center gap-2 px-3 py-2.5">
        <span className="text-[var(--color-brand)]">{icon}</span>
        <h3 className="flex-1 font-display text-xs font-semibold">{title}</h3>
        {action}
        {fact && <ProvenanceChip fact={fact} />}
      </header>

      <div className="px-3 pb-3">
        {state === "empty" && (
          <div className="rounded-xl bg-[var(--color-surface-2)] px-3 py-2.5">
            <p className="flex items-start gap-1.5 text-[11px] leading-relaxed text-[var(--color-ink-faint)]">
              <IconInfo size="0.9em" className="mt-0.5 shrink-0" />
              {hint}
            </p>
            {/* The button sends the same sentence the traveller would have
                typed, rather than calling a tool directly. Everything then
                flows through the one path that keeps the conversation, the
                memory and the trace consistent - and the transcript still
                reads as something a person said. */}
            {onAsk && ask && (
              <button
                type="button"
                onClick={() => onAsk(ask)}
                className="mt-2 inline-flex min-h-8 items-center gap-1 rounded-full border border-[var(--color-brand)]/40 bg-[var(--color-brand-soft)] px-2.5 text-[11px] font-medium text-[var(--color-brand-strong)] transition-colors duration-200 hover:border-[var(--color-brand)]"
              >
                {askLabel}
              </button>
            )}
          </div>
        )}
        {state === "loading" && <div className="skeleton h-20 w-full rounded-xl" />}
        {state === "ready" && children}
      </div>
    </section>
  );
}

/**
 * Where a panel's numbers came from.
 *
 * Two visually distinct states rather than one label with different text,
 * because the difference between a measured forecast and an invented price is
 * the single most important thing on the panel and must survive a glance.
 */
function ProvenanceChip({ fact }: { fact: TripFact }) {
  if (fact.simulated) {
    return (
      <span
        title={`Generated by the ${fact.source} provider. Not real availability or pricing.`}
        className="rounded-full bg-[var(--color-warn-soft)] px-2 py-0.5 text-[10px] font-semibold uppercase tracking-wide text-[var(--color-warn)]"
      >
        Simulated
      </span>
    );
  }
  return (
    <span
      title={`Live data from ${fact.source}.`}
      className="rounded-full bg-[var(--color-mint-soft)] px-2 py-0.5 text-[10px] font-medium text-[var(--color-mint)]"
    >
      {fact.source}
    </span>
  );
}

function Row({ label, value }: { label: string; value: React.ReactNode }) {
  return (
    <div className="flex items-baseline justify-between gap-3 py-1 text-[11px]">
      <span className="text-[var(--color-ink-faint)]">{label}</span>
      <span className="min-w-0 truncate text-right font-medium">{value}</span>
    </div>
  );
}

